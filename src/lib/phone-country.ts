/** Country for an IANA time zone, or null when the zone is unknown or missing. */
export function countryFromTimeZone(timeZone: string | null | undefined): string | null {
  if (!timeZone) return null;
  const direct = TIME_ZONE_COUNTRY[timeZone];
  if (direct) return direct;
  // Any other US zone ("America/Indiana/Knox", "America/North_Dakota/Center", ...).
  if (/^America\/(Indiana|Kentucky|North_Dakota)\//.test(timeZone)) return "US";
  return null;
}

/**
 * Loose phone check for the contact form: only the characters people type in phone numbers, and
 * 6 to 15 digits (15 is the E.164 maximum). Catches typos like "abc" or "12" without rejecting any
 * real format ("0332 5983077", "+92 332-598-3077", "(212) 555 0101").
 */
export function isPlausiblePhone(value: string): boolean {
  const text = value.trim();
  if (!/^[0-9+()\-.\s]+$/.test(text)) return false;
  const digits = text.replace(/\D/g, "").length;
  return digits >= 6 && digits <= 15;
}
