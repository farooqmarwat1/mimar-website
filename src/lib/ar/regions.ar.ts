export function regionKey(region: Region): string | undefined {
  return Object.keys(regions).find((key) => regions[key].path === region.path);
}

/**
 * The region in the page language. English returns it untouched. For Arabic
 * the text fields come from the overlay (visible body copy with Eastern
 * digits); path, slugs, phones, geo, GBP links and `area` codes stay as in the
 * English data. Metadata fields keep Western digits.
 */
export function localizeRegion(region: Region, lang: Locale): Region {
  if (lang !== "ar") return region;
  const key = regionKey(region);
  const ar = key ? overlays[key] : undefined;
  if (!ar) return region;
  const d = (value: string) => localizeDigits(value, lang);
  return {
    ...region,
    name: ar.name,
    city: ar.city,
    seoTitle: ar.seoTitle,
    description: ar.description,
    keywords: ar.keywords,
    h1: ar.h1,
    intro: ar.intro,
    marketCopy: d(ar.marketCopy),
    services: ar.services.map((s) => ({ title: d(s.title), body: d(s.body) })),
    reasons: ar.reasons.map((r) => ({ title: d(r.title), body: d(r.body) })),
    office: { ...region.office, city: ar.office.city, country: ar.office.country, address: d(ar.office.address) },
    locations: region.locations.map((location, index) => {
      const overlay = ar.locations[index];
      return overlay
        ? {
            ...location,
            city: overlay.city,
            streetAddress: d(overlay.streetAddress),
            postalCode: location.postalCode ? d(location.postalCode) : undefined,
          }
        : location;
    }),
    currency: ar.currency,
    compliance: ar.compliance.map(d),
    testimonials: region.testimonials.map((t, index) => ({
      name: t.name,
      quote: d(ar.testimonials[index]?.quote ?? t.quote),
      city: ar.testimonials[index]?.city ?? t.city,
    })),
    faqs: ar.faqs.map((f) => ({ question: d(f.question), answer: d(f.answer) })),
    keyFacts: ar.keyFacts.map(d),
  };
}

